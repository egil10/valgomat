def main() -> None:
    root = Path(__file__).resolve().parent.parent
    qfile = root / "web" / "public" / "data" / "questions.json"
    data = json.loads(qfile.read_text(encoding="utf-8"))
    parties_meta = data["parties"]

    existing_ids = {q["id"] for q in data["questions"]}
    existing_statements = {q["statement"].strip().lower() for q in data["questions"]}

    new_questions: list[dict] = []
    used_ids = set(existing_ids)
    for topic, statement, axis, kernel, scores in RAW:
        if statement.strip().lower() in existing_statements:
            continue
        for slug in PARTIES:
            assert slug in scores, f"missing {slug} for {statement!r}"
            assert 1 <= scores[slug] <= 7, f"bad score for {slug} in {statement!r}"
        base = slugify(statement)[:50] or slugify(topic)
        qid = base
        n = 2
        while qid in used_ids:
            qid = f"{base}-{n}"
            n += 1
        used_ids.add(qid)
        new_questions.append(make_q(qid, topic, statement, axis, kernel, scores, parties_meta))

    data["questions"].extend(new_questions)
    qfile.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"appended {len(new_questions)} questions, total = {len(data['questions'])}")


if __name__ == "__main__":
    main()
