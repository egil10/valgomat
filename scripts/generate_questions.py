"""Generate ~280 valgomat statements with party scores and concise paraphrased
positions. Output is appended to the existing 23 hand-written questions to
produce a full pool of ~300.

Scoring philosophy
==================
Each statement names a *policy axis*. For every party we record a 1–7 score
on a "Helt uenig … Helt enig" agree/disagree scale where 4 = ambivalent.
Scores come from each party's well-established ideological stance on that
axis (party programs 2025–2029, public manifestos, voting records). Quotes
are *paraphrased* position summaries, not direct citations — the prototype
links readers to the full program for verification.

This is a quantitative scaffolding meant to be progressively refined with
real PDF-anchored quotes; not a substitute for proper RAG over the program
corpus.
"""
from __future__ import annotations

import json
import re
import unicodedata
from pathlib import Path

PARTIES = ["ap", "frp", "hoyre", "sv", "sp", "rodt", "mdg", "krf", "venstre"]


def slugify(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = re.sub(r"[^a-zA-Z0-9]+", "-", text).strip("-").lower()
    return text[:60]


# Party-specific "vil"-phrasing for concise paraphrases.
PARTY_VERB = {
    "ap": "Arbeiderpartiet",
    "frp": "Fremskrittspartiet",
    "hoyre": "Høyre",
    "sv": "SV",
    "sp": "Senterpartiet",
    "rodt": "Rødt",
    "mdg": "MDG",
    "krf": "KrF",
    "venstre": "Venstre",
}


def stance_phrase(score: int, statement_kernel: str) -> str:
    """Convert a score and the verb-kernel of the statement to a stance phrase."""
    s = statement_kernel
    if score >= 6:
        return f"er enig — {s}."
    if score == 5:
        return f"støtter i hovedsak forslaget, men vil ha justeringer på hvordan {s}."
    if score == 4:
        return f"er åpne for å vurdere, men har ikke programfestet at {s}."
    if score == 3:
        return f"er skeptisk og mener at det er bedre alternativer enn at {s}."
    if score == 2:
        return f"er uenig og vil ikke at {s}."
    return f"avviser forslaget og mener tvert imot at {s} er feil retning."


def make_q(
    qid: str,
    topic: str,
    statement: str,
    axis: str,
    kernel: str,
    scores: dict[str, int],
    parties_meta: dict[str, dict],
) -> dict:
    positions = {}
    for slug in PARTIES:
        score = scores[slug]
        positions[slug] = {
            "score": score,
            "quote": f"{PARTY_VERB[slug]} {stance_phrase(score, kernel)}",
            "source_url": parties_meta[slug]["program_url"],
        }
    return {
        "id": qid,
        "topic": topic,
        "statement": statement,
        "axis": axis,
        "positions": positions,
    }


